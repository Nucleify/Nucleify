import { existsSync, readFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'

export type EmitSibling = 'vue' | 'react' | 'solid' | 'svelte' | 'css'

export function emitBaseName(sourcePath: string): string {
  return basename(sourcePath).replace(/\.nuc\.tsx$/, '')
}

export function nucPathFromEmit(emitPath: string): string {
  const dir = dirname(emitPath)
  const base = basename(emitPath).replace(/\.(vue|tsx|svelte|css)$/, '')
  return join(dir, `${base}.nuc.tsx`)
}

export function siblingPath(nucPath: string, kind: EmitSibling): string {
  const dir = dirname(nucPath)
  const base = emitBaseName(nucPath)
  if (kind === 'vue') return join(dir, `${base}.vue`)
  if (kind === 'react') return join(dir, `${base}.tsx`)
  if (kind === 'svelte') return join(dir, `${base}.svelte`)
  return join(dir, `${base}.css`)
}

/** True when a `.tsx` emit is Solid (vs React `'use client'` / `--from=react`). */
export function isSolidEmitSource(contents: string): boolean {
  if (!contents.includes('@generated by nucleify-compiler')) return false
  if (contents.includes("'use client'") || /import --from=react\b/.test(contents)) return false
  return (
    /from\s+['"]solid-js['"]/.test(contents) ||
    /build --app=solid\b/.test(contents) ||
    /import --from=solid\b/.test(contents)
  )
}

export function resolveImportPath(cwd: string, inputPath: string): {
  componentPath: string
  kind: 'vue' | 'react' | 'solid' | 'svelte' | 'css'
} {
  const abs = resolve(cwd, inputPath)
  if (abs.endsWith('.nuc.tsx')) {
    throw new Error(
      'import: pass .vue / .tsx / .svelte / .css emit path, not *.nuc.tsx (use build for authoring)',
    )
  }
  if (abs.endsWith('.vue')) return { componentPath: abs, kind: 'vue' }
  if (abs.endsWith('.tsx')) {
    if (existsSync(abs) && isSolidEmitSource(readFileSync(abs, 'utf8'))) {
      return { componentPath: abs, kind: 'solid' }
    }
    return { componentPath: abs, kind: 'react' }
  }
  if (abs.endsWith('.svelte')) return { componentPath: abs, kind: 'svelte' }
  if (abs.endsWith('.css')) {
    const base = basename(abs, '.css')
    const dir = dirname(abs)
    const vue = join(dir, `${base}.vue`)
    const tsx = join(dir, `${base}.tsx`)
    const svelte = join(dir, `${base}.svelte`)
    if (existsSync(vue)) return { componentPath: vue, kind: 'vue' }
    if (existsSync(tsx)) {
      if (isSolidEmitSource(readFileSync(tsx, 'utf8'))) {
        return { componentPath: tsx, kind: 'solid' }
      }
      return { componentPath: tsx, kind: 'react' }
    }
    if (existsSync(svelte)) return { componentPath: svelte, kind: 'svelte' }
    throw new Error(`import: no sibling .vue/.tsx/.svelte for ${inputPath}`)
  }
  throw new Error(`import: expected .vue, .tsx, .svelte, or .css path, got ${inputPath}`)
}

export function inferComponentName(base: string): string {
  return base
    .split(/[_-]/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('')
}

export function isGeneratedEmit(contents: string, kind: EmitSibling): boolean {
  if (kind === 'vue' || kind === 'svelte') {
    return contents.includes('<!-- @generated by nucleify-compiler -->')
  }
  if (kind === 'react' || kind === 'solid') {
    return contents.includes('// @generated by nucleify-compiler')
  }
  return contents.includes('/* @generated by nucleify-compiler */')
}
